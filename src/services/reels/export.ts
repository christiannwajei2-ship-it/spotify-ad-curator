// generateFFmpegScript
// ===================================================

/**
 * Basic FFmpeg command suggestions — useful as a starting point for
 * developers rendering the template programmatically.
 */
export function generateFFmpegScript(template: VideoTemplate): string {
  const lines: string[] = [
    `#!/bin/bash`,
    `# FFmpeg Script — ${template.name}`,
    `# Generated by SpotifyAdCurator on ${new Date().toLocaleDateString()}`,
    `# Duration: ${template.totalDurationMs / 1000}s | Format: 1080x1920 (9:16)`,
    ``,
    `# Prerequisites: ffmpeg >= 5.0`,
    `# Replace INPUT_VIDEO with your actual video file paths.`,
    ``,
    `OUTPUT="output_${template.id}.mp4"`,
    ``,
  ];

  template.sections.forEach((section, idx) => {
    const startSec = (section.startMs / 1000).toFixed(2);
    const durSec = (section.durationMs / 1000).toFixed(2);
    lines.push(`# --- Section ${idx + 1}: ${section.label} (${startSec}s – ${(parseFloat(startSec) + parseFloat(durSec)).toFixed(2)}s) ---`);
    lines.push(`# Background colour: ${section.backgroundColorHex} | Animation: ${section.animationStyle}`);

    section.textOverlays.forEach((overlay, oIdx) => {
      const delay = (overlay.animationDelay ?? 0) / 1000;
      const textStart = parseFloat(startSec) + delay;
      lines.push(
        `# Text overlay ${oIdx + 1}: "${overlay.content}" @ ${overlay.position} [${overlay.fontSize}] from ${textStart.toFixed(2)}s`
      );
    });

    lines.push(
      `ffmpeg -i INPUT_VIDEO_${idx}.mp4 \\`,
      `  -ss ${startSec} -t ${durSec} \\`,
      `  -vf "scale=1080:1920:force_original_aspect_ratio=decrease,pad=1080:1920:(ow-iw)/2:(oh-ih)/2:${section.backgroundColorHex}" \\`,
      `  -c:v libx264 -preset fast -crf 22 \\`,
      `  segment_${idx}.mp4`,
      ``
    );
  });

  lines.push(
    `# Create concat list`,
    `cat > concat_list.txt << 'EOF'`,
    ...template.sections.map((_, idx) => `file 'segment_${idx}.mp4'`),
    `EOF`,
    ``,
    `# Concatenate segments`,
    `ffmpeg -f concat -safe 0 -i concat_list.txt -c copy "$OUTPUT"`,
    ``,
    `echo "Done! Output: $OUTPUT"`,
  );

  return lines.join('\n');
}
