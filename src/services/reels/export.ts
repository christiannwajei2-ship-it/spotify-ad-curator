/**
 * Full template data as a JSON string — ideal for custom video editors.
 */
export function exportAsJSON(template: VideoTemplate): string {
  return JSON.stringify(template, null, 2);
}

// ===================================================
// exportAsShotList
// ===================================================

/**
 * Human-readable shot list in markdown format.
 */
export function exportAsShotList(template: VideoTemplate): string {
  const shots = generateShotList(template);
  const lines: string[] = [
    `# Shot List — ${template.name}`,
    `**Duration:** ${template.totalDurationMs / 1000}s  |  **Category:** ${template.category}`,
    `**Formats:** ${template.formats.join(', ')}`,
    '',
    '---',
    '',
  ];

  for (const shot of shots) {
    lines.push(`## Shot ${shot.shotNumber} — ${shot.sectionLabel}`);
    lines.push(`**Time:** ${shot.startTime} → ${shot.endTime} (${shot.durationSec}s)`);
    lines.push(`**Visual:** ${shot.visualDescription}`);
    lines.push(`**Animation:** ${shot.animationStyle}`);
    if (shot.textOverlays.length > 0) {
      lines.push(`**Text Overlays:**`);
      shot.textOverlays.forEach((t) => lines.push(`  - ${t}`));
    }
    if (shot.notes) {
      lines.push(`**Production Note:** ${shot.notes}`);
    }
    lines.push('');
  }

  lines.push('---');
  lines.push(`*Generated by SpotifyAdCurator · ${new Date().toLocaleDateString()}*`);

  return lines.join('\n');
}

// ===================================================
// exportAsCSV
// ===================================================

/**
 * Spreadsheet-friendly CSV — one row per text overlay.
 */
export function exportAsCSV(template: VideoTemplate): string {
  const header = [
    'Shot #',
    'Section',
    'Start (s)',
    'End (s)',
    'Duration (s)',
    'Text Content',
    'Position',
    'Font Size',
    'Color',
    'Animation',
    'Animation Delay (ms)',
    'Bold',
    'Italic',
    'Notes',
  ].join(',');

  const rows: string[] = [header];

  template.sections.forEach((section, idx) => {
    const startSec = (section.startMs / 1000).toFixed(1);
    const endSec = ((section.startMs + section.durationMs) / 1000).toFixed(1);
    const durSec = (section.durationMs / 1000).toFixed(1);

    if (section.textOverlays.length === 0) {
      rows.push(
        [
          idx + 1,
          section.label,
          startSec,
          endSec,
          durSec,
          '(no text)',
          '',
          '',
          '',
          section.animationStyle,
          '',
          '',
          '',
          section.notes ?? '',
        ]
          .map((v) => `"${String(v).replace(/"/g, '""')}"`)
          .join(',')
      );
    } else {
      section.textOverlays.forEach((overlay) => {
        rows.push(
          [
            idx + 1,
            section.label,
            startSec,
            endSec,
            durSec,
            overlay.content,
            overlay.position,
            overlay.fontSize,
            overlay.color,
            overlay.animation,
            overlay.animationDelay ?? 0,
            overlay.bold ? 'Yes' : 'No',
            overlay.italic ? 'Yes' : 'No',
            section.notes ?? '',
          ]
            .map((v) => `"${String(v).replace(/"/g, '""')}"`)
            .join(',')
        );
      });
    }
  });

  return rows.join('\n');
}

