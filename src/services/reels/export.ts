// generateCapCutProject
// ===================================================

/**
 * CapCut-compatible project structure (JSON).
 * Based on CapCut desktop project schema conventions.
 */
export function generateCapCutProject(template: VideoTemplate): string {
  const tracks = template.sections.map((section, idx) => ({
    id: `track_${idx}`,
    type: 'video',
    start: section.startMs * 1000, // CapCut uses microseconds
    duration: section.durationMs * 1000,
    extra_material_refs: [],
    clip: {
      alpha: 1.0,
      flip: { horizontal: false, vertical: false },
      rotation: 0.0,
      scale: { x: 1.0, y: 1.0 },
      transform: { x: 0.0, y: 0.0 },
    },
    color: section.backgroundColorHex,
    animation: section.animationStyle,
  }));

  const textTracks = template.sections.flatMap((section, secIdx) =>
    section.textOverlays.map((overlay, oIdx) => ({
      id: `text_${secIdx}_${oIdx}`,
      type: 'text',
      start: (section.startMs + (overlay.animationDelay ?? 0)) * 1000,
      duration: (section.durationMs - (overlay.animationDelay ?? 0)) * 1000,
      content: overlay.content,
      style: {
        font_size: overlay.fontSize,
        color: overlay.color,
        bold: overlay.bold ?? false,
        italic: overlay.italic ?? false,
        position: overlay.position,
      },
      animation: {
        in: overlay.animation,
        out: 'fade',
      },
    }))
  );

  const project = {
    id: `capcut_${template.id}_${Date.now()}`,
    name: template.name,
    create_time: Math.floor(Date.now() / 1000),
    fps: 30,
    duration: template.totalDurationMs * 1000,
    canvas_config: {
      width: 1080,
      height: 1920,
      ratio: '9:16',
    },
    color_space: 0,
    tracks,
    text_tracks: textTracks,
    description: template.description,
    generated_by: 'SpotifyAdCurator',
  };

  return JSON.stringify(project, null, 2);
}

